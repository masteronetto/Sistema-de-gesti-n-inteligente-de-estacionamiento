-- Esquema base para Supabase del sistema de estacionamiento.
-- Incluye tipos, tablas, indices, RLS, triggers y datos semilla iniciales.

begin;

create extension if not exists pgcrypto;

do $$
begin
  create type parking_space_type as enum ('simple', 'doble_fondo', 'doble_frente');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type parking_space_status as enum ('disponible', 'ocupado', 'alerta', 'mantenimiento', 'reservado');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type parking_alert_status as enum ('NUEVO', 'ESCALADA');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type app_role as enum ('guardia', 'jefe_seguridad', 'servicios_generales');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text unique,
  full_name text,
  role app_role not null default 'guardia',
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.parking_spaces (
  id text primary key,
  zone text not null,
  type parking_space_type not null,
  status parking_space_status not null default 'disponible',
  pair_id text unique,
  plate text,
  driver_name text,
  phone text,
  entry_time time,
  maintenance_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint parking_spaces_pair_self_check check (pair_id is null or pair_id <> id)
);

alter table public.parking_spaces
  drop constraint if exists parking_spaces_pair_id_fkey;

alter table public.parking_spaces
  add constraint parking_spaces_pair_id_fkey
  foreign key (pair_id)
  references public.parking_spaces (id)
  on delete set null
  deferrable initially deferred;

create index if not exists parking_spaces_zone_idx on public.parking_spaces (zone);
create index if not exists parking_spaces_status_idx on public.parking_spaces (status);
create index if not exists parking_spaces_type_idx on public.parking_spaces (type);

create table if not exists public.parking_sessions (
  id uuid primary key default gen_random_uuid(),
  space_id text not null references public.parking_spaces (id) on delete cascade,
  user_id uuid references auth.users (id) on delete set null,
  plate text,
  driver_name text,
  phone text,
  zone text not null,
  space_type parking_space_type not null,
  entry_time timestamptz not null default now(),
  exit_time timestamptz,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint parking_sessions_status_check check (status in ('active', 'closed'))
);

create index if not exists parking_sessions_space_id_idx on public.parking_sessions (space_id);
create index if not exists parking_sessions_status_idx on public.parking_sessions (status);
create index if not exists parking_sessions_entry_time_idx on public.parking_sessions (entry_time desc);

create table if not exists public.parking_alerts (
  id bigint generated by default as identity primary key,
  plate text not null,
  blocked_space_id text not null references public.parking_spaces (id) on delete cascade,
  blocker_space_id text not null references public.parking_spaces (id) on delete cascade,
  driver_name text not null,
  phone text not null,
  status parking_alert_status not null default 'NUEVO',
  seconds_remaining integer not null default 300 check (seconds_remaining >= 0),
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint parking_alerts_spaces_different check (blocked_space_id <> blocker_space_id)
);

create index if not exists parking_alerts_status_idx on public.parking_alerts (status);
create index if not exists parking_alerts_created_at_idx on public.parking_alerts (created_at desc);

create table if not exists public.parking_activity_log (
  id bigint generated by default as identity primary key,
  space_id text references public.parking_spaces (id) on delete set null,
  session_id uuid references public.parking_sessions (id) on delete set null,
  alert_id bigint references public.parking_alerts (id) on delete set null,
  actor_role app_role,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists parking_activity_log_created_at_idx on public.parking_activity_log (created_at desc);
create index if not exists parking_activity_log_space_id_idx on public.parking_activity_log (space_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

