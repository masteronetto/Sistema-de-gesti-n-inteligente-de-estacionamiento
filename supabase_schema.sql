create or replace function public.sync_session_on_space_change()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'ocupado' then
    if new.entry_time is null then
      new.entry_time = (now() at time zone 'UTC')::time;
    end if;

    if not exists (
      select 1
      from public.parking_sessions
      where space_id = new.id
        and status = 'active'
    ) then
      insert into public.parking_sessions (
        space_id,
        plate,
        driver_name,
        phone,
        zone,
        space_type,
        entry_time,
        status
      )
      values (
        new.id,
        new.plate,
        new.driver_name,
        new.phone,
        new.zone,
        new.type,
        now(),
        'active'
      );
    end if;
  elsif old.status = 'ocupado' and new.status = 'disponible' then
    update public.parking_sessions
      set exit_time = now(),
          status = 'closed'
    where space_id = new.id
      and status = 'active';

    new.plate = null;
    new.driver_name = null;
    new.phone = null;
    new.entry_time = null;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_sync_session_on_space_change on public.parking_spaces;
create trigger trg_sync_session_on_space_change
before update on public.parking_spaces
for each row execute function public.sync_session_on_space_change();

